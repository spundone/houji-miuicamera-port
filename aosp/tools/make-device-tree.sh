#!/usr/bin/env bash
# Writes the ROM device tree (aosp/device) with a patched camera APK in it, ready to commit as
# its own repository and sync into a ROM at device/xiaomi/houji-miuicamera-port.
#
#   aosp/tools/make-device-tree.sh PATCHED_APK OUT_DIR [--leica LEICA_PORT_APK]
#
# PATCHED_APK is the unsigned output of aosp/tools/patch-apk.sh. It is split into 90 MB parts
# (prebuilt/MiuiCamera.apk.part-aa, -ab, ...), which Android.bp joins at build time. With
# --leica, the community Leica port's processor, libraries and models go in leica/, installed to
# /system/etc/xcam17/leica for Essential Moment. OUT_DIR's .git, if any, is kept.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
apk="" out="" leica=""
while [ $# -gt 0 ]; do
    case "$1" in
        --leica) leica="$2"; shift ;;
        *) if [ -z "$apk" ]; then apk="$1"; else out="$1"; fi ;;
    esac
    shift
done
[ -n "$apk" ] && [ -n "$out" ] || { echo "usage: $0 PATCHED_APK OUT_DIR [--leica LEICA_PORT_APK]" >&2; exit 2; }
[ -f "$apk" ] || { echo "no such file: $apk" >&2; exit 1; }

mkdir -p "$out"
find "$out" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
cp -R "$ROOT/aosp/device/." "$out/"
mkdir -p "$out/prebuilt"
split -b 90m "$apk" "$out/prebuilt/MiuiCamera.apk.part-"
sum=$(shasum -a 256 "$apk" | cut -d' ' -f1)
echo "$sum  MiuiCamera.apk" > "$out/prebuilt/MiuiCamera.apk.sha256"
cat "$out"/prebuilt/MiuiCamera.apk.part-* | shasum -a 256 | grep -q "^$sum " \
    || { echo "parts don't join back to the APK" >&2; exit 1; }
echo "$out: device tree with $(ls "$out"/prebuilt/MiuiCamera.apk.part-* | wc -l | tr -d ' ') APK parts ($sum)"

[ -n "$leica" ] || exit 0
unzip -q -l "$leica" assets/legend18/provenance.json >/dev/null \
    || { echo "$leica is not the Leica port (no assets/legend18)" >&2; exit 1; }
dir="$out/leica"
rm -rf "$dir" && mkdir -p "$dir/lib"
# The Leica port's code and models; the Leica Moment build adds a second engine in classes13-15
# with its lm_ models. Its AI composition models aren't used.
files='^classes1[1-9]\.dex$|^assets/(legend18|leica-v4|leica-v43-ui|lm-ui)/|^assets/(leica_filter_param_|lm_)|^assets/(scene-transfer\.bin|leica-color-v3\.rgb)$'
# shellcheck disable=SC2046
unzip -o -q "$leica" $(unzip -Z1 "$leica" | grep -E "$files") -d "$dir"
# The port's own native libraries: those the camera APK doesn't have, and the C++ runtime its
# helper programs load from the same folder.
have=$(unzip -Z1 "$apk" 'lib/arm64-v8a/*')
for lib in $(unzip -Z1 "$leica" 'lib/arm64-v8a/*' | grep '\.so$'); do
    [ "$lib" != lib/arm64-v8a/libc++_shared.so ] && echo "$have" | grep -qx "$lib" && continue
    unzip -o -q -p "$leica" "$lib" > "$dir/lib/${lib##*/}"
done
[ -f "$dir/classes11.dex" ] && [ -f "$dir/lib/libmonopan_runner.so" ] || { echo "Leica port files incomplete" >&2; exit 1; }

# Libraries through Soong (Make refuses ELF files in PRODUCT_COPY_FILES); the rest copied.
{
    echo "// Generated by aosp/tools/make-device-tree.sh: the Leica port's native libraries and helper"
    echo "// programs, installed to /system/etc/xcam17/leica/lib."
    for f in "$dir"/lib/*.so; do
        n=${f##*/}
        printf '\nprebuilt_etc {\n    name: "xcam17_leica_%s",\n    src: "lib/%s",\n    sub_dir: "xcam17/leica/lib",\n    filename_from_src: true,\n}\n' "${n%.so}" "$n"
    done
} > "$dir/Android.bp"
{
    echo "# Generated by aosp/tools/make-device-tree.sh: Leica Essential's files, at /system/etc/xcam17/leica."
    echo "LEICA_PATH := \$(MIUICAMERA_PORT_PATH)/leica"
    echo
    echo "PRODUCT_COPY_FILES += \\"
    for f in "$dir"/classes*.dex; do
        n=${f##*/}
        echo "    \$(LEICA_PATH)/$n:\$(TARGET_COPY_OUT_SYSTEM)/etc/xcam17/leica/$n \\"
    done
    echo "    \$(call find-copy-subdir-files,*,\$(LEICA_PATH)/assets,\$(TARGET_COPY_OUT_SYSTEM)/etc/xcam17/leica/assets)"
    echo
    echo "PRODUCT_PACKAGES += \\"
    for f in "$dir"/lib/*.so; do n=${f##*/}; echo "    xcam17_leica_${n%.so} \\"; done
    echo
} > "$dir/leica.mk"
{
    echo "# Generated by aosp/tools/make-device-tree.sh: the Leica port starts these as programs."
    for f in "$dir"/lib/*_runner.so; do
        printf '\n[system/etc/xcam17/leica/lib/%s]\nmode: 0755\nuser: AID_ROOT\ngroup: AID_ROOT\ncaps: 0\n' "${f##*/}"
    done
} > "$dir/config.fs"
echo "$dir: Leica port files ($(du -sh "$dir" | cut -f1))"
